const { withDatabase } = require('./db.cjs');
withDatabase(async client => {
  await client.query(`
    CREATE SCHEMA IF NOT EXISTS bookclub_l1;
    CREATE TABLE IF NOT EXISTS bookclub_l1.categories (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name varchar(40) NOT NULL UNIQUE
    );
    CREATE TABLE IF NOT EXISTS bookclub_l1.books (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      category_id integer NOT NULL REFERENCES bookclub_l1.categories(id),
      title varchar(120) NOT NULL CHECK (length(trim(title)) > 0),
      author varchar(120) NOT NULL CHECK (length(trim(author)) > 0),
      description varchar(2000) NOT NULL DEFAULT '',
      recommendation varchar(500) NOT NULL CHECK (length(trim(recommendation)) > 0),
      seed_key varchar(60) UNIQUE,
      created_at timestamptz NOT NULL DEFAULT now()
    );
    CREATE INDEX IF NOT EXISTS books_category_id_idx ON bookclub_l1.books(category_id);
  `);
  console.log('Level 1 분야·책 테이블이 준비되었습니다. 다른 스키마는 변경하지 않았습니다.');
});
